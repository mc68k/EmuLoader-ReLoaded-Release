#!/usr/bin/env python3
"""Writes lang/en_GB.ini, the British English language file, from the program's texts.

EmuLoader's texts are in US English. This file gives the British spelling of every text
that has a word spelt differently (colour, grey, centre, favourite, customise ...); the
other texts aren't in the file, so they show in US English, as an empty line would.

Run it after make_language_template.py when texts change:
    python3 tools/make_british.py
Lines filled in by hand in lang/en_GB.ini are kept (they win over the generated ones).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_language_template as m  # noqa: E402

# US -> UK, whole words (the case of the first letter, or of the whole word, is kept).
WORDS = {}


def add(us, uk, suffixes=("",)):
    for s in suffixes:
        WORDS[us + s] = uk + s


add("color", "colour", ("", "s", "ed", "ing", "ful", "less"))
add("gray", "grey", ("", "s", "ed", "ing", "scale", "ish"))
add("center", "centre", ("", "s"))
WORDS.update({"centered": "centred", "centering": "centring"})
add("behavior", "behaviour", ("", "s", "al"))
add("neighbor", "neighbour", ("", "s", "ing", "hood"))
add("honor", "honour", ("", "s", "ed"))
add("favor", "favour", ("", "s", "ed", "ite", "ites", "able"))
add("humor", "humour")
add("flavor", "flavour", ("", "s"))
add("armor", "armour")
add("labor", "labour")
WORDS.update({"canceled": "cancelled", "canceling": "cancelling", "labeled": "labelled", "labeling": "labelling",
              "modeled": "modelled", "modeling": "modelling", "traveled": "travelled", "traveling": "travelling",
              "leveled": "levelled", "leveling": "levelling", "signaled": "signalled", "signaling": "signalling",
              "totaled": "totalled", "fulfill": "fulfil", "enroll": "enrol", "defense": "defence",
              "offense": "offence", "catalog": "catalogue", "catalogs": "catalogues", "analog": "analogue",
              "dialogue": "dialogue", "artifact": "artefact", "artifacts": "artefacts", "jewelry": "jewellery",
              "aluminum": "aluminium", "judgment": "judgement", "acknowledgment": "acknowledgement",
              "skeptical": "sceptical", "plow": "plough", "mold": "mould", "cozy": "cosy"})
for v in ("analyz", "paralyz", "catalyz"):
    for us, uk in (("e", "e"), ("ed", "ed"), ("es", "es"), ("ing", "ing"), ("er", "er"), ("ers", "ers")):
        WORDS[v + us] = v[:-1] + "s" + uk
# -ize / -ization -> -ise / -isation, for these words only ("size", "prize" ... stay).
IZE = ("custom", "initial", "maxim", "minim", "local", "synchron", "organ", "recogn", "optim", "normal",
       "priorit", "summar", "categor", "final", "visual", "author", "random", "real", "util", "special",
       "standard", "emphas", "apolog", "memor", "character", "capital", "central", "general", "personal",
       "serial", "symbol", "stabil", "steril", "harmon", "critic", "familiar", "legal", "modern", "symmetr")
for stem in IZE:
    for us, uk in (("ize", "ise"), ("ized", "ised"), ("izes", "ises"), ("izing", "ising"), ("ization", "isation"),
                   ("izations", "isations"), ("izer", "iser"), ("izers", "isers"), ("izable", "isable")):
        WORDS[stem + us] = stem + uk
WORDS["unrecognized"] = "unrecognised"
WORDS["uncategorized"] = "uncategorised"
WORDS = {k: v for k, v in WORDS.items() if k != v}

# Not inside file names, paths and identifiers (favorites\favorites.txt, favorite_title, TColor).
WORD_RX = re.compile(r"(?<![\w\\/._-])(" + "|".join(sorted(WORDS, key=len, reverse=True)) + r")(?![\w\\/_?*]|\.\w)",
                     re.IGNORECASE)


def british(text):
    def sub(mt):
        w = mt.group(0)
        uk = WORDS[w.lower()]
        if w.isupper() and len(w) > 1:
            return uk.upper()
        return uk[0].upper() + uk[1:] if w[0].isupper() else uk
    return WORD_RX.sub(sub, text)


def write_compact(path, texts, trans, header):
    """Only the texts spelt differently: a text that isn't in the file (or is empty) shows
    as it is, in US English."""
    lines = ["; EmuLoader ReLoaded language file (UTF-8): English (UK).",
             "; EmuLoader's texts are in US English; this file gives the ones spelt differently in",
             "; British English (colour, grey, centre, favourites, customise ...). Any text that isn't",
             "; here shows in US English. Each line is: US English text=British English text.",
             "; Generated by tools/make_british.py; lines changed by hand are kept when it runs again.",
             "",
             "[Language]"]
    lines += ["%s=%s" % (k, v) for k, v in header.items()]
    for sec, lst, _ in m.grouped(texts):
        found = {}
        for ctx in m.contexts_of(sec):
            for src, uk in trans.get(ctx, {}).items():
                found.setdefault(src, uk)
        done = [src for src in lst if found.get(src)]
        if not done:
            continue
        lines += ["", "[%s]" % sec]
        lines += [m.escape(src, True) + "=" + m.escape(found[src], False) for src in done]
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    texts = m.Texts()
    m.menu_texts(texts)
    m.code_texts(texts)
    m.form_texts(texts)
    path = os.path.join(m.ROOT, "lang", "en_GB.ini")
    old, header = m.read_lang(path) if os.path.exists(path) else ({}, {})
    header = {"Name": header.get("Name", "English (UK)"), "Locale": header.get("Locale", "en_GB"),
              **{k: v for k, v in header.items() if k not in ("Name", "Locale")}}
    trans = {}
    n = 0
    for ctx, lst in texts.order.items():
        for s in lst:
            uk = old.get(ctx, {}).get(s) or british(s)
            if uk != s:
                trans.setdefault(ctx, {})[s] = uk
                n += 1
    write_compact(path, texts, trans, header)
    print("%s: %d texts in British spelling" % (path, n))


if __name__ == "__main__":
    main()
